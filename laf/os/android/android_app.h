#ifndef OS_ANDROID_ANDROID_APP_H_INCLUDED
#define OS_ANDROID_ANDROID_APP_H_INCLUDED
#pragma once

#include "os/mobile.h"

#include <string>
#include <vector>

struct android_app;
struct ANativeWindow;

namespace os {

// Internal state accessors (used by the backend implementation).
android_app* android_get_app();
void android_set_app(android_app* app);
ANativeWindow* android_native_window();

// Processes all pending Android looper events (input, lifecycle
// commands, etc.). If timeoutMs is -1 it waits indefinitely until
// one event is received.
void android_process_events(int timeoutMs);

// Returns true when the activity is being destroyed.
bool android_is_destroy_requested();

// Screen density in dots-per-inch (e.g. 160 for mdpi, 480 for xxhdpi).
int android_screen_dpi();

// Returns the unicode character generated by the given Android key
// code and meta state (uses android.view.KeyEvent.getUnicodeChar()).
int android_get_unicode_char(int keyCode, int metaState);

// Short vibration to indicate that a long-press was recognized.
void android_haptic_feedback();

// Opens the given URL/file with an external Android app.
bool android_open_url(const std::string& url);

// Files received through "Open with..." intents before the app was
// ready to process them.
std::vector<std::string> android_take_pending_files();

} // namespace os

#endif
